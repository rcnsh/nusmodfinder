// @ts-check
// Generates src/fts-separators.js: every code point FTS5's `unicode61`
// tokenizer (as declared by migrations/0006_fts_external.sql, default
// options) treats as a separator, probed from SQLite itself.
//
//   node scripts/gen-fts-separators.mjs          # rewrite the file
//   node scripts/gen-fts-separators.mjs --check  # exit 1 if it is stale
//
// Why a table and not `[^\p{L}\p{N}]`: unicode61 classifies by Unicode 6.1
// (code points assigned later are token characters, even emoji), keeps the
// combining diacritics it can strip as token characters (U+0308 in a
// decomposed "naïve") and splits on every other mark. FINDINGS B8.
import { readFile, writeFile } from 'node:fs/promises';
import { DatabaseSync } from 'node:sqlite';
import { fileURLToPath } from 'node:url';

const OUT = fileURLToPath(new URL('../src/fts-separators.js', import.meta.url));
const SURROGATES = [0xd800, 0xdfff];

/**
 * Code point ranges `[from, to]` (inclusive) unicode61 treats as separators.
 * Lone surrogates cannot be stored as UTF-8, so they are listed as separators.
 * @returns {[number, number][]}
 */
export function probeSeparators() {
  const db = new DatabaseSync(':memory:');
  db.exec(`CREATE VIRTUAL TABLE t USING fts5(x, tokenize = 'porter unicode61');
           CREATE VIRTUAL TABLE v USING fts5vocab(t, 'instance');`);
  const insert = db.prepare('INSERT INTO t(rowid, x) VALUES (?, ?)');
  db.exec('BEGIN');
  // "x<c>y" is one token when <c> is a token character, two when it separates.
  for (let c = 0; c <= 0x10ffff; c++) {
    if (c >= SURROGATES[0] && c <= SURROGATES[1]) continue;
    insert.run(c + 1, `x${String.fromCodePoint(c)}y`);
  }
  db.exec('COMMIT');
  const token = new Set(db.prepare('SELECT doc FROM v GROUP BY doc HAVING count(*) = 1').all()
    .map((r) => Number(r.doc) - 1));
  db.close();
  /** @type {[number, number][]} */
  const ranges = [];
  for (let c = 0; c <= 0x10ffff; c++) {
    const separator = (c >= SURROGATES[0] && c <= SURROGATES[1]) || !token.has(c);
    if (!separator) continue;
    const last = ranges[ranges.length - 1];
    if (last && last[1] === c - 1) last[1] = c;
    else ranges.push([c, c]);
  }
  return ranges;
}

/** @param {[number, number][]} ranges */
export function render(ranges) {
  const hex = (/** @type {number} */ c) => c.toString(16);
  const list = ranges.map(([a, b]) => (a === b ? hex(a) : `${hex(a)}-${hex(b)}`));
  /** @type {string[]} */
  const lines = [];
  for (let i = 0; i < list.length; i += 12) lines.push(`  '${list.slice(i, i + 12).join(',')}',`);
  return `// @ts-check
// GENERATED by scripts/gen-fts-separators.mjs from SQLite's FTS5 unicode61
// tokenizer; do not edit. The code points (hex, inclusive ranges) unicode61
// treats as separators: a run of them splits a query into tokens exactly where
// the modules_fts tokenizer splits text (FINDINGS B8). Built with RegExp
// rather than written as a literal because the ranges start and end on
// combining marks, which a literal class would render misleadingly.
const RANGES = [
${lines.join('\n')}
].join(',');

const cls = RANGES.split(',').map((r) => r.split('-').map((h) => \`\\\\u{\${h}}\`).join('-')).join('');

export const FTS_SEPARATORS = new RegExp(\`[\${cls}]+\`, 'u');
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render(probeSeparators());
  if (process.argv.includes('--check')) {
    const current = await readFile(OUT, 'utf8').catch(() => '');
    if (current !== text) {
      console.error('src/fts-separators.js is stale: run node scripts/gen-fts-separators.mjs');
      process.exit(1);
    }
    console.log('src/fts-separators.js is current');
  } else {
    await writeFile(OUT, text);
    console.log(`wrote ${OUT}`);
  }
}
